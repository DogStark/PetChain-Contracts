// ============================================================
// Chain-of-custody canonical digest tests (Issue: custody history)
//
// `get_custody_chain_digest` produces a SHA-256 hash chain over the
// custody history in canonical (append) order:
//
//     state = sha256(domain || u32be(version) || u64be(pet_id))
//     for each entry in chain order:
//         state = sha256(state || u32be(len(entry_bytes)) || entry_bytes)
//     digest = sha256(state || u32be(sequence))
//
// entry_bytes is the canonical serialisation of a CustodyEntry
// (see `PetChainContract::canonical_custody_entry_bytes`):
//
//     u32be(len(from_xdr)) || from_xdr
//     || u32be(len(to_xdr)) || to_xdr
//     || u64be(timestamp)
//     || u32be(transfer_type)   // Direct=0, Adoption=1, Multisig=2
//
// where from_xdr/to_xdr are the soroban Address ScVal XDR encodings
// (SCV_ADDRESS=18 || SC_ADDRESS_TYPE_ACCOUNT=0 || KEY_TYPE_ED25519=0
// || 32-byte ed25519 key, 44 bytes total for account addresses).
//
// The vectors below were generated by the reference implementation in
// scripts/gen_custody_digest_vectors.py and are *published*: they must not
// change unless the canonical format (domain/version/serialisation) changes.
// ============================================================

use crate::{
    ContractError, CustodyChainDigest, CustodyEntry, Gender, PetChainContract,
    PetChainContractClient, PrivacyLevel, Species, SystemKey, TransferType,
};
use soroban_sdk::{testutils::Address as _, Address, Env, Error, String, Vec};

// Fixed deterministic account strkeys used by the published vectors.
// A0 is the canonical all-zero ed25519 account key; A1..A3 are derived
// deterministic keys (payload == index as u32be).
const A0: &str = "GAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAWHF";
const A1: &str = "GAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAC6PV";
const A2: &str = "GAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAEGWF";
const A3: &str = "GAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAAGO6V";

// Published digest vectors (see header comment for the construction).
const EMPTY_PET1: &str = "fd563dbadd4dc31365d995ee354f59e8156e499bb3f88618b0cd656e85bb5002";
const ONE_PET1: &str = "2ea66e7a5426d4b46fbd23238b81e91835a94c0c32b370fceef1da78db2e2701";
const TWO_PET1: &str = "ec36d1f293582df34bef1575aba01b8c12560e55771cb816d4bdc670e0135fbe";
const THREE_PET1: &str = "9357d526ad37944aae12dc8ecff7034afbd401b69e3e3913fd22fe16bd394842";
const REORDERED_PET1: &str = "1265e034f391c9233c9231c5e89fd8634401342ceef889d0bb842287dbc2f71c";
const TAMPERED_TO_PET1: &str = "f1a878686671708d444fc124e42458f6997f9845bbcf28e33c493d29c7301853";
const TWO_PET7: &str = "367ab935bd7019e3e1a96e7fa2ca8b1c30f0eb65cefed1184f3c0747fea18ae2";

fn setup(env: &Env) -> (PetChainContractClient, Address, Address) {
    env.mock_all_auths();
    env.budget().reset_unlimited();
    let contract_id = env.register_contract(None, PetChainContract);
    let client = PetChainContractClient::new(env, &contract_id);
    let owner = Address::generate(env);
    client.init_admin(&owner);
    (client, owner, contract_id)
}

fn register_pet(client: &PetChainContractClient, env: &Env, owner: &Address) -> u64 {
    client.register_pet(
        owner,
        &String::from_str(env, "Buddy"),
        &String::from_str(env, "2020-01-01"),
        &Gender::Male,
        &Species::Dog,
        &String::from_str(env, "Labrador"),
        &String::from_str(env, "Golden"),
        &30,
        &None,
        &PrivacyLevel::Public,
    )
}

fn addr(env: &Env, strkey: &str) -> Address {
    Address::from_string(&String::from_str(env, strkey))
}

fn entry(
    env: &Env,
    from: &str,
    to: &str,
    timestamp: u64,
    transfer_type: TransferType,
) -> CustodyEntry {
    CustodyEntry {
        from: addr(env, from),
        to: addr(env, to),
        timestamp,
        transfer_type,
    }
}

fn chain(env: &Env, entries: &[CustodyEntry]) -> Vec<CustodyEntry> {
    let mut v = Vec::new(env);
    for e in entries {
        v.push_back(e.clone());
    }
    v
}

fn set_custody_chain(env: &Env, contract_id: &Address, pet_id: u64, chain: &Vec<CustodyEntry>) {
    env.as_contract(contract_id, || {
        env.storage()
            .instance()
            .set(&SystemKey::CustodyChain(pet_id), chain);
    });
}

fn hex_to_array(hex: &str) -> [u8; 32] {
    let mut out = [0u8; 32];
    let bytes = hex.as_bytes();
    for i in 0..32 {
        let hi = (bytes[2 * i] as char).to_digit(16).unwrap() as u8;
        let lo = (bytes[2 * i + 1] as char).to_digit(16).unwrap() as u8;
        out[i] = (hi << 4) | lo;
    }
    out
}

fn assert_digest_equals(_env: &Env, result: &CustodyChainDigest, expected_hex: &str) {
    assert_eq!(
        result.digest.to_array(),
        hex_to_array(expected_hex),
        "digest mismatch for pet_id={} sequence={}",
        result.pet_id,
        result.sequence
    );
}

fn assert_common_fields(env: &Env, result: &CustodyChainDigest, pet_id: u64) {
    assert_eq!(
        result.domain,
        String::from_str(env, crate::CUSTODY_DIGEST_DOMAIN)
    );
    assert_eq!(result.version, crate::CUSTODY_DIGEST_VERSION);
    assert_eq!(result.pet_id, pet_id);
}

