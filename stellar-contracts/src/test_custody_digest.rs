/// The custody view is capped at MAX_CUSTODY_CHAIN: a full chain is
/// returned, the (cap + 1)th append is rejected with TooManyItems, and the
/// digest over the full chain reports the correct sequence.
#[test]
fn custody_chain_view_is_bounded_at_max() {
    let env = Env::default();
    let (client, owner, _contract_id) = setup(&env);
    let pet_id = register_pet(&client, &env, &owner);
    client.activate_pet(&pet_id);

    let owner_a = owner.clone();
    let owner_b = Address::generate(&env);

    // Drive the chain to its cap through the real append path.
    for i in 0..crate::MAX_CUSTODY_CHAIN {
        if i % 2 == 0 {
            client.transfer_pet(&owner_a, &pet_id, &owner_b);
        } else {
            client.transfer_pet(&owner_b, &pet_id, &owner_a);
        }
    }

    // The view is bounded: exactly MAX_CUSTODY_CHAIN entries are returned.
    let chain = client.get_custody_chain(&pet_id);
    assert_eq!(chain.len(), crate::MAX_CUSTODY_CHAIN);

    // One more append is rejected at the boundary.
    let err = client
        .try_transfer_pet(&owner_a, &pet_id, &owner_b)
        .unwrap_err()
        .unwrap();
    assert_eq!(err, Error::from(ContractError::TooManyItems));

    // The digest still computes over the full bounded chain.
    let result = client.get_custody_chain_digest(&pet_id);
    assert_eq!(result.sequence, crate::MAX_CUSTODY_CHAIN);
}

/// Digest computation over a full (cap-sized) chain is resource-bounded:
/// it completes and consumes a modest, fixed amount of CPU and memory
/// regardless of the entry contents.
#[test]
fn digest_computation_is_resource_bounded() {
    let env = Env::default();
    let (client, owner, contract_id) = setup(&env);
    let pet_id = register_pet(&client, &env, &owner);

    // Seed a full chain directly (fast path to the cap).
    let mut entries = Vec::new(&env);
    for i in 0..crate::MAX_CUSTODY_CHAIN {
        entries.push_back(entry(
            &env,
            A0,
            A1,
            1_000_000_000 + i as u64,
            TransferType::Direct,
        ));
    }
    set_custody_chain(&env, &contract_id, pet_id, &entries);

    let cpu_before = env.budget().cpu_instruction_cost();
    let mem_before = env.budget().memory_bytes_cost();

    let result = client.get_custody_chain_digest(&pet_id);

    let cpu_used = env.budget().cpu_instruction_cost() - cpu_before;
    let mem_used = env.budget().memory_bytes_cost() - mem_before;

    assert_eq!(result.sequence, crate::MAX_CUSTODY_CHAIN);
    // Native test-mode metering charges ~62M instructions for a full chain;
    // the bound is deliberately generous to catch only accidental blow-ups
    // (e.g. quadratic serialisation), not exact host costs.
    assert!(
        cpu_used < 150_000_000,
        "digest over {}-entry chain consumed too much CPU: {cpu_used}",
        crate::MAX_CUSTODY_CHAIN
    );
    // Native test-mode metering charges ~6.5MB for a full chain (per-call
    // host-object overhead, linear in entry count); the bound only guards
    // against accidental super-linear blow-ups.
    assert!(
        mem_used < 20_000_000,
        "digest over {}-entry chain consumed too much memory: {mem_used}",
        crate::MAX_CUSTODY_CHAIN
    );
}
