// Behavioural tamper cases (no hardcoded constants)
// ---------------------------------------------------------------

fn digest_of(client: &PetChainContractClient, pet_id: u64) -> [u8; 32] {
    client.get_custody_chain_digest(&pet_id).digest.to_array()
}

#[test]
fn appending_entry_changes_digest() {
    let env = Env::default();
    let (client, owner, _contract_id) = setup(&env);
    let pet_id = register_pet(&client, &env, &owner);

    let empty = digest_of(&client, pet_id);
    assert_eq!(empty, hex_to_array(EMPTY_PET1));

    // First transfer appends one entry.
    let b = Address::generate(&env);
    client.transfer_pet(&owner, &pet_id, &b);
    let after_one = digest_of(&client, pet_id);
    assert_ne!(
        after_one, empty,
        "appending an entry must change the digest"
    );

    // Second transfer appends another entry.
    let c = Address::generate(&env);
    client.transfer_pet(&b, &pet_id, &c);
    let after_two = digest_of(&client, pet_id);
    assert_ne!(after_two, after_one, "each append must change the digest");

    assert_eq!(client.get_custody_chain_digest(&pet_id).sequence, 2);
}

#[test]
fn reordering_entries_changes_digest() {
    let env = Env::default();
    let (client, owner, contract_id) = setup(&env);
    let pet_id = register_pet(&client, &env, &owner);

    let e1 = entry(&env, A0, A1, 1_000_000_000, TransferType::Direct);
    let e2 = entry(&env, A1, A2, 2_000_000_000, TransferType::Adoption);

    set_custody_chain(
        &env,
        &contract_id,
        pet_id,
        &chain(&env, &[e1.clone(), e2.clone()]),
    );
    let ordered = digest_of(&client, pet_id);

    set_custody_chain(&env, &contract_id, pet_id, &chain(&env, &[e2, e1]));
    let reordered = digest_of(&client, pet_id);

    assert_ne!(
        ordered, reordered,
        "reordering entries must change the digest"
    );
}

#[test]
fn tampering_any_field_changes_digest() {
    let env = Env::default();
    let (client, owner, contract_id) = setup(&env);
    let pet_id = register_pet(&client, &env, &owner);

    let original = entry(&env, A0, A1, 1_000_000_000, TransferType::Direct);

    // Same entry with one field changed each time.
    let tampered_from = entry(&env, A2, A1, 1_000_000_000, TransferType::Direct);
    let tampered_to = entry(&env, A0, A2, 1_000_000_000, TransferType::Direct);
    let tampered_ts = entry(&env, A0, A1, 1_000_000_001, TransferType::Direct);
    let tampered_type = entry(&env, A0, A1, 1_000_000_000, TransferType::Adoption);

    set_custody_chain(&env, &contract_id, pet_id, &chain(&env, &[original]));
    let baseline = digest_of(&client, pet_id);

    for mutated in [tampered_from, tampered_to, tampered_ts, tampered_type] {
        set_custody_chain(&env, &contract_id, pet_id, &chain(&env, &[mutated]));
        assert_ne!(
            digest_of(&client, pet_id),
            baseline,
            "altering a custody entry field must change the digest"
        );
    }
}

